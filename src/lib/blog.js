export function getArticleBySlug(slug) {
    return articles.find((article) => article.slug === slug);
}

export function getRelatedArticles(article, limit = 3) {
    return articles
        .filter((candidate) => candidate.slug !== article.slug && candidate.categorySlug === article.categorySlug)
        .concat(articles.filter((candidate) => candidate.slug !== article.slug && candidate.categorySlug !== article.categorySlug))
        .slice(0, limit);
}
